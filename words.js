// Virtual themes that mix several real ones.
const MIXES = [
    {
        id: 'random', name: 'Random mix', emoji: '🎲', adult: false,
        blurb: 'A bit of everything, family-friendly.',
    },
    {
        id: 'chaos', name: 'Anything goes (18+)', emoji: '🔥', adult: true,
        blurb: 'Everything, including the Fish Against Humanity pack. Not for kids.',
    },
];

const DEFAULT_THEME = 'random';

const entry = ([text, def]) => ({ text, def });
const byTheme = new Map(THEMES.map((t) => [t.id, t.words.map(entry)]));
const allFamily = THEMES.filter((t) => !t.adult).flatMap((t) => byTheme.get(t.id));
const everything = THEMES.flatMap((t) => byTheme.get(t.id));
const definitions = new Map(everything.map((w) => [w.text.toLowerCase(), w.def]));

const shuffled = (list) => {
    const a = [...list];
    for (let i = a.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [a[i], a[j]] = [a[j], a[i]];
    }
    return a;
};

const isTheme = (id) => typeof id === 'string' && (MIXES.some((m) => m.id === id) || byTheme.has(id));

function poolFor(id) {
    if (id === 'random') return allFamily;
    if (id === 'chaos') return everything;
    return byTheme.get(id) || allFamily;
}

// Themes for the host's drop-down, in display order (mixes first, adult pack last).
function publicThemes() {
    const list = [...MIXES, ...THEMES].map((t) => ({
        id: t.id, name: t.name, emoji: t.emoji, adult: t.adult, blurb: t.blurb, count: poolFor(t.id).length,
    }));
    return list.sort((a, b) => Number(a.adult) - Number(b.adult) || 0);
}

// Picks up to `count` distinct words for a theme, skipping anything in `exclude` (lowercase texts).
// If the theme runs dry, tops up from the matching mix so a big game still gets enough words.
function pickWords(themeId, count, exclude = new Set()) {
    const chosen = [];
    const seen = new Set(exclude);
    const take = (pool) => {
        for (const w of shuffled(pool)) {
            if (chosen.length >= count) return;
            const key = w.text.toLowerCase();
            if (seen.has(key)) continue;
            seen.add(key);
            chosen.push(w);
        }
    };
    take(poolFor(themeId));
    if (chosen.length < count) take(poolFor(THEMES.find((t) => t.id === themeId)?.adult ? 'chaos' : 'random'));
    return chosen;
}

const lookupDef = (text) => definitions.get(String(text).trim().toLowerCase()) || null;

module.exports = { THEMES, DEFAULT_THEME, isTheme, publicThemes, pickWords, lookupDef };
